"""Build the data file for the static website in docs/.

Reads the raw transaction CSVs, keeps Pink Morsel rows, and writes daily revenue
and units per region to docs/data.js. Run it again whenever the raw data changes:

    python build_site.py
"""
import glob
import json
import os

import pandas as pd

PRICE_CHANGE = "2021-01-15"
REGIONS = ["north", "east", "south", "west"]


def load_pink_morsels(data_dir="data"):
    files = sorted(glob.glob(os.path.join(data_dir, "daily_sales_data_*.csv")))
    if not files:
        raise SystemExit(f"No daily_sales_data_*.csv files found in {data_dir}/")
    df = pd.concat((pd.read_csv(f) for f in files), ignore_index=True)
    df = df[df["product"].str.strip().str.lower() == "pink morsel"].copy()
    df["price"] = pd.to_numeric(df["price"].astype(str).str.replace("$", "", regex=False))
    df["quantity"] = pd.to_numeric(df["quantity"])
    df["date"] = pd.to_datetime(df["date"])
    df["region"] = df["region"].str.strip().str.lower()
    df["sales"] = df["quantity"] * df["price"]
    return df


def main():
    df = load_pink_morsels()
    dates = pd.date_range(df["date"].min(), df["date"].max(), freq="D")
    payload = {"start": dates[0].strftime("%Y-%m-%d"), "days": len(dates), "priceChange": PRICE_CHANGE,
               "priceBefore": float(df.loc[df["date"] < PRICE_CHANGE, "price"].median()),
               "priceAfter": float(df.loc[df["date"] >= PRICE_CHANGE, "price"].median()),
               "regions": {}}
    for region in REGIONS:
        daily = df[df["region"] == region].groupby("date")[["sales", "quantity"]].sum().reindex(dates, fill_value=0)
        payload["regions"][region] = {"revenue": [round(v, 2) for v in daily["sales"]],
                                      "units": [int(v) for v in daily["quantity"]]}
    os.makedirs("docs", exist_ok=True)
    with open("docs/data.js", "w") as fh:
        fh.write("// Generated by build_site.py. Do not edit by hand.\n")
        fh.write("window.SALES = " + json.dumps(payload, separators=(",", ":")) + ";\n")
    print(f"Wrote docs/data.js: {len(dates)} days x {len(REGIONS)} regions")


if __name__ == "__main__":
    main()
